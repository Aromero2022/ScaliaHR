"use client";

import Link from "next/link";
import { usePathname, useRouter } from "next/navigation";
import { createClient } from "@/lib/supabase/client";
import { clsx } from "clsx";
import type { ModuleFlags } from "@/lib/tenant/module-flags";
import { NAV_ITEMS, filterNavByFlags } from "@/lib/navigation/nav-config";

type NavItem = {
  href: string;
  label: string;
  icon: React.ComponentType<{ active: boolean }>;
  moduleFlag?: keyof ModuleFlags;
};

const iconMap: Record<string, React.ComponentType<{ active: boolean }>> = {
  "/dashboard": HomeIcon,
  "/employees": EmployeesIcon,
  "/profile": UserIcon,
  "/org-chart": OrgIcon,
  "/performance": PerformanceIcon,
  "/lms": LmsIcon,
  "/skills-hub": SkillsIcon,
  "/admin/arco": ShieldIcon,
  "/admin-center": AdminIcon,
};

const navItems: NavItem[] = NAV_ITEMS.map((item) => ({
  ...item,
  icon: iconMap[item.href] ?? HomeIcon,
}));

export default function Sidebar({
  moduleFlags,
}: {
  moduleFlags: ModuleFlags | null;
}) {
  const pathname = usePathname();
  const router = useRouter();
  const supabase = createClient();

  async function handleSignOut() {
    await supabase.auth.signOut();
    router.push("/login");
    router.refresh();
  }

  const visibleItems = filterNavByFlags(navItems, moduleFlags) as NavItem[];

  return (
    <aside className="flex h-screen w-64 shrink-0 flex-col border-r border-slate-800 bg-slate-900">
      <div className="flex h-16 items-center gap-2 border-b border-slate-800 px-6">
        <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-indigo-600 text-sm font-bold text-white">
          S
        </div>
        <span className="text-lg font-bold text-white">Scalia HR</span>
      </div>

      <nav className="flex-1 space-y-1 px-3 py-4">
        {visibleItems.map((item) => {
          const active = pathname === item.href || pathname.startsWith(item.href + "/");
          return (
            <Link
              key={item.href}
              href={item.href}
              className={clsx(
                "flex items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium transition",
                active
                  ? "bg-indigo-600/10 text-indigo-400"
                  : "text-slate-400 hover:bg-slate-800 hover:text-slate-200"
              )}
            >
              <item.icon active={active} />
              {item.label}
            </Link>
          );
        })}
      </nav>

      <div className="border-t border-slate-800 p-3">
        <button
          onClick={handleSignOut}
          className="flex w-full items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium text-slate-400 transition hover:bg-slate-800 hover:text-red-400"
        >
          <LogoutIcon />
          Cerrar Sesión
        </button>
      </div>
    </aside>
  );
}

